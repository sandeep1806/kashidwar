#!/usr/bin/env node
// Writes lib/guides.generated.ts: one static import per content/guides/*.json and per blog post
// in content/blog/*.json, so a new guide or post (for example one written by the content
// review) needs no code change. Runs before `next dev` and `next build` (package.json). The
// output is git-ignored. Guides and posts share one translation file per locale
// (content/guides/i18n/<locale>.json, keyed by slug), so their slugs must not collide.
import { existsSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const list = (dir) => (existsSync(join(root, dir)) ? readdirSync(join(root, dir)).filter((f) => f.endsWith(".json") && f !== "calendar.json").sort() : []);
const guides = list("content/guides");
const posts = list("content/blog");
const clash = posts.filter((f) => guides.includes(f));
if (clash.length) throw new Error(`[guides] blog post slugs also used by guides: ${clash.join(", ")}`);
const id = (p, f) => p + f.replace(/\.json$/, "").replace(/[^a-zA-Z0-9]/g, "_");
const out = [
  "// Generated by scripts/gen-guides-index.mjs — do not edit.",
  ...guides.map((f) => `import ${id("g_", f)} from "@/content/guides/${f}";`),
  ...posts.map((f) => `import ${id("b_", f)} from "@/content/blog/${f}";`),
  "",
  `export const guideFiles: unknown[] = [${guides.map((f) => id("g_", f)).join(", ")}];`,
  `export const postFiles: unknown[] = [${posts.map((f) => id("b_", f)).join(", ")}];`,
  "",
].join("\n");
writeFileSync(join(root, "lib/guides.generated.ts"), out);
console.log(`[guides] ${guides.length} guides and ${posts.length} blog posts indexed`);
