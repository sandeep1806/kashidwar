#!/usr/bin/env node
// Writes lib/guides.generated.ts: one static import per content/guides/*.json, so a new
// guide (for example one written by the content review) needs no code change. Runs
// before `next dev` and `next build` (package.json). The output is git-ignored.
import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const files = readdirSync(join(root, "content/guides")).filter((f) => f.endsWith(".json")).sort();
const id = (f) => "g_" + f.replace(/\.json$/, "").replace(/[^a-zA-Z0-9]/g, "_");
const out = [
  "// Generated by scripts/gen-guides-index.mjs — do not edit.",
  ...files.map((f) => `import ${id(f)} from "@/content/guides/${f}";`),
  "",
  `export const guideFiles: unknown[] = [${files.map(id).join(", ")}];`,
  "",
].join("\n");
writeFileSync(join(root, "lib/guides.generated.ts"), out);
console.log(`[guides] ${files.length} guides indexed`);
